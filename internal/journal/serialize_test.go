// TestTimestampFromRealtime locks CPython's round-half-even microsecond
// rounding of datetime.fromtimestamp(float).
func TestTimestampFromRealtime(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		seconds float64
		want    string
	}{
		{1728475023.123456, "2024-10-09T11:57:03.123456"},
		{5e-7, "1970-01-01T00:00:00"},               // 0.5 rounds to even 0
		{1.5e-6, "1970-01-01T00:00:00.000002"},      // 1.5 rounds to even 2
		{2.5e-6, "1970-01-01T00:00:00.000002"},      // 2.5 rounds to even 2
		{1728475023.9999995, "2024-10-09T11:57:04"}, // 999999.5 carries
		{1e9, "2001-09-09T01:46:40"},
	} {
		got, err := TimestampFromRealtime(tc.seconds)
		if err != nil {
			t.Errorf("TimestampFromRealtime(%v): %v", tc.seconds, err)
			continue
		}
		if want := tc.want; pythonISOFormat(got) != want {
			t.Errorf("TimestampFromRealtime(%v) = %s, want %s", tc.seconds, pythonISOFormat(got), want)
		}
	}
	if _, err := TimestampFromRealtime(253402300800.0); err == nil {
		t.Error("TimestampFromRealtime(year 10000) should error like Python ValueError")
	}
	for _, seconds := range []float64{math.NaN(), 1e19, -1e19} {
		if _, err := TimestampFromRealtime(seconds); err == nil {
			t.Errorf("TimestampFromRealtime(%v) should error like Python fromtimestamp range checks", seconds)
		}
	}
}

// TestSerializeValues covers the value shapes that only occur outside the
// golden fixtures: bool/nil/json.Number extras, nested lists and objects,
// and the UnicodeDecodeError parity for undecodable bytes.
func TestSerializeValues(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name   string
		fields []Field
		want   string
	}{
		{"empty", nil, "{}"},
		{"bool and null", []Field{{Key: "a", Value: true}, {Key: "b", Value: nil}}, `{"a": true, "b": null}`},
		{"int64", []Field{{Key: "n", Value: int64(-7)}}, `{"n": -7}`},
		{"big int verbatim", []Field{{Key: "n", Value: json.Number("10000000000000000000000000")}}, `{"n": 10000000000000000000000000}`},
		{"nested list", []Field{{Key: "m", Value: []any{int64(1), "x", nil}}}, `{"m": [1, "x", null]}`},
		{"nested ordered object", []Field{{Key: "o", Value: []Field{{Key: "y", Value: int64(2)}, {Key: "x", Value: int64(1)}}}}, `{"o": {"y": 2, "x": 1}}`},
	} {
		got, err := Serialize(tc.fields)
		if err != nil {
			t.Errorf("%s: %v", tc.name, err)
			continue
		}
		if string(got) != tc.want {
			t.Errorf("%s = %s, want %s", tc.name, got, tc.want)
		}
	}
	if _, err := Serialize([]Field{{Key: "MESSAGE", Value: []byte("\xff")}}); err == nil {
		t.Error("Serialize should refuse undecodable bytes like Python UnicodeDecodeError")
	}
	// Unordered objects must be refused, not reordered: the wire format is
	// Python construction order, so callers supply []Field in document
	// order (config decoding captures it in the Task 16 wiring).
	if _, err := Serialize([]Field{{Key: "o", Value: map[string]any{"x": int64(1)}}}); err == nil {
		t.Error("Serialize should refuse map[string]any values")
	}
}

// TestSetField locks Python dict item assignment: overwrite keeps the
// original construction position, append goes last.
func TestSetField(t *testing.T) {
	t.Parallel()
	fields := []Field{{Key: "MESSAGE", Value: "x"}, {Key: "PID", Value: int64(1)}}
	fields = SetField(fields, "PID", int64(2))
	fields = SetField(fields, "timestamp", "t")
	want := []Field{{Key: "MESSAGE", Value: "x"}, {Key: "PID", Value: int64(2)}, {Key: "timestamp", Value: "t"}}
	assertFieldsEqual(t, want, fields)
}

// TestMergeExtraFields locks dict.update semantics: existing keys are
// overwritten in place, new keys are appended in document order.
func TestMergeExtraFields(t *testing.T) {
	t.Parallel()
	fields := MergeExtraFields(
		[]Field{{Key: "MESSAGE", Value: "original"}, {Key: "PRIORITY", Value: int64(6)}},
		[]Field{{Key: "MESSAGE", Value: "overwritten"}, {Key: "cluster", Value: "c-1"}},
	)
	want := []Field{{Key: "MESSAGE", Value: "overwritten"}, {Key: "PRIORITY", Value: int64(6)}, {Key: "cluster", Value: "c-1"}}
	assertFieldsEqual(t, want, fields)
}

func assertFieldsEqual(t *testing.T, want, got []Field) {
	t.Helper()
	if len(want) != len(got) {
		t.Fatalf("field count: want %d, got %d (%v)", len(want), len(got), got)
	}
	for i := range want {
		if want[i] != got[i] {
			t.Errorf("field %d: want %+v, got %+v", i, want[i], got[i])
		}
	}
}
