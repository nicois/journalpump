// TestSerializeGolden asserts byte-identical output against
// serialization_golden.jsonl, which is generated by actually running the
// Python pipeline (PumpReader.convert_entry/get_next +
// JournalObjectHandler.process/_get_or_generate_json + json.dumps) — see
// testdata/generate_golden.py. The invalid-UTF-8 fixture proves the
// repr()-style fallback keeps raw invalid bytes off the wire (spec §4.4,
// quirk D8).
func TestSerializeGolden(t *testing.T) {
	t.Parallel()
	expected := make(map[string]string)
	raw, err := os.ReadFile(filepath.Join("testdata", "serialization_golden.jsonl"))
	if err != nil {
		t.Fatalf("read golden file: %v", err)
	}
	for _, line := range strings.Split(strings.TrimRight(string(raw), "\n"), "\n") {
		var golden struct {
			Name   string `json:"name"`
			Output string `json:"output"`
		}
		if err := json.Unmarshal([]byte(line), &golden); err != nil {
			t.Fatalf("decode golden line: %v", err)
		}
		expected[golden.Name] = golden.Output
	}
	if len(expected) != len(goldenFixtures) {
		t.Fatalf("golden file has %d fixtures but the test table has %d", len(expected), len(goldenFixtures))
	}
	for _, fixture := range goldenFixtures {
		want, ok := expected[fixture.name]
		if !ok {
			t.Errorf("golden file has no fixture named %q", fixture.name)
			continue
		}
		got := string(runSerializationPipeline(t, fixture))
		if got != want {
			t.Errorf("fixture %q:\n got: %s\nwant: %s", fixture.name, got, want)
		}
	}
}

// runSerializationPipeline ports the full Python path:
// get_next enrichment -> convert_entry -> process() rewriting ->
// _get_or_generate_json timestamp/extra_field_values -> json.dumps.
func runSerializationPipeline(t *testing.T, fixture goldenFixture) []byte {
	t.Helper()
	fields := SetField(fixture.entry, "__REALTIME_TIMESTAMP", fixture.realtime)
	if seqnum, ok := ParseSeqnumFromCursor(fixture.cursor); ok {
		fields = SetField(fields, "__SEQNUM", seqnum)
	}
	fields = ProcessEntry(ConvertEntry(fields))
	timestamp, err := TimestampFromRealtime(float64(fixture.realtime) / 1e6)
	if err != nil {
		t.Fatalf("timestamp: %v", err)
	}
	fields = SetField(fields, "timestamp", timestamp)
	fields = MergeExtraFields(fields, fixture.extras)
	out, err := Serialize(fields)
	if err != nil {
		t.Fatalf("serialize: %v", err)
	}
	return out
}

// TestPythonFloatRepr locks the float rendering json.dumps uses (Python
// repr): shortest round-trip digits, scientific notation for decimal
// exponents < -4 or >= 16 — both bounds differ from Go's formatting.
func TestPythonFloatRepr(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		value float64
		want  string
	}{
		{60.0, "60.0"},
		{1e-05, "1e-05"},
		{1e20, "1e+20"},
		{0.0001, "0.0001"},
		{1e15, "1000000000000000.0"},
		{1e16, "1e+16"},
		{0.5, "0.5"},
		{123.456, "123.456"},
		{math.Copysign(0, -1), "-0.0"},
		{0.0, "0.0"},
		{1e100, "1e+100"},
		{2.5e-05, "2.5e-05"},
		{1.5e16, "1.5e+16"},
		{6e7, "60000000.0"},
		{math.NaN(), "NaN"},
		{math.Inf(1), "Infinity"},
		{math.Inf(-1), "-Infinity"},
	} {
		if got := pythonFloatRepr(tc.value); got != tc.want {
			t.Errorf("pythonFloatRepr(%v) = %q, want %q", tc.value, got, tc.want)
		}
	}
}

// TestPythonJSONString locks the ensure_ascii=True escaping json.dumps
// uses: short escapes, \u00xx lowercase control/DEL escapes, \uxxxx for
// non-ASCII BMP characters and UTF-16 surrogate pairs for astral ones.
func TestPythonJSONString(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		value string
		want  string
	}{
		{`"quoted" \backslash`, `"\"quoted\" \\backslash"`},
		{"héllo 世界", `"h\u00e9llo \u4e16\u754c"`},
		{"😀", `"\ud83d\ude00"`},
		{"DEL\x7f ctl\x01\t\n", `"DEL\u007f ctl\u0001\t\n"`},
		{"", `""`},
		{"ascii", `"ascii"`},
	} {
		if got := pythonJSONString(tc.value); got != tc.want {
			t.Errorf("pythonJSONString(%q) = %s, want %s", tc.value, got, tc.want)
		}
	}
}

