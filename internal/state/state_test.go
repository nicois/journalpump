// TestReadCorruptJSON mirrors Python: only FileNotFoundError is caught
// in load_state; a corrupt file makes json.load raise and the daemon
// crash at startup — Go returns the error for the caller to fail on.
func TestReadCorruptJSON(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name    string
		content []byte
	}{
		{name: "truncated file", content: []byte(`{"readers": {"r": {"cur`)},
		{name: "trailing garbage", content: []byte(`{"readers": {}} trailing`)},
		{name: "not an object", content: []byte(`[1, 2, 3]`)},
		{name: "invalid utf-8", content: []byte{'{', 0xff, '}'}},
	}
	for _, tc := range tests {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			path := filepath.Join(t.TempDir(), "state.json")
			if err := os.WriteFile(path, tc.content, 0o600); err != nil {
				t.Fatal(err)
			}
			if _, err := Read(path); err == nil {
				t.Fatal("expected an error for a corrupt state file")
			}
		})
	}
}

// TestReadMalformedSenderCrashes mirrors Python's unconditional
// sender["sent"]["cursor"] (journalpump.py:896): a sender object
// without the sent.cursor path must be an ERROR (the daemon crashes),
// never a silent nil cursor that would trigger a full resync.
func TestReadMalformedSenderCrashes(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		sender string
	}{
		{name: "sent missing", sender: `{"type": "LogSender"}`},
		{name: "cursor missing", sender: `{"sent": {"count": 1}}`},
	}
	for _, tc := range tests {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			file := fmt.Sprintf(`{
    "readers": {
        "r": {
            "cursor": null,
            "searches": {},
            "senders": {"alpha": %s},
            "total_bytes": 0,
            "total_lines": 0
        }
    },
    "start_time": "x"
}`, tc.sender)
			path := filepath.Join(t.TempDir(), "state.json")
			if err := os.WriteFile(path, []byte(file), 0o600); err != nil {
				t.Fatal(err)
			}
			_, err := Read(path)
			if err == nil || !strings.Contains(err.Error(), "missing sent.cursor") {
				t.Fatalf("err = %v, want missing sent.cursor error", err)
			}
		})
	}
}

// readHandCrafted parses a hand-crafted state file (raw bytes on disk,
// unsorted sender keys) via the Read path.
func readHandCrafted(t *testing.T, content string) *State {
	t.Helper()
	path := filepath.Join(t.TempDir(), "state.json")
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	state, err := Read(path)
	if err != nil {
		t.Fatalf("Read: %v", err)
	}
	return state
}
