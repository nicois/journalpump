const pythonFixture = "testdata/state_python_written.json"

// quirkStateFile is hand-crafted: the senders object lists zulu before
// alpha, so the file key order is NOT the sorted order Python's
// sort_keys=True would ever produce (captured Python files are always
// alphabetical; the quirk can only come from hand-edited or
// foreign-written files).
const quirkStateFile = `{
    "readers": {
        "r": {
            "cursor": "cursor=reader-0",
            "searches": {"errors": 2},
            "senders": {
                "zulu": {
                    "type": "LogSender",
                    "buffer": {"cursor": null, "entry_num": 0, "current_queue": 0, "total_size": 0},
                    "sent": {"cursor": "cursor=Z", "count": 1, "bytes": 2},
                    "health": {"status": "connected", "elapsed": 1.5, "errors": []}
                },
                "alpha": {
                    "type": "LogSender",
                    "buffer": {"cursor": null, "entry_num": 0, "current_queue": 0, "total_size": 0},
                    "sent": {"cursor": "cursor=A", "count": 3, "bytes": 4},
                    "health": {"status": "connected", "elapsed": 0.5, "errors": []}
                }
            },
            "total_bytes": 0,
            "total_lines": 0
        }
    },
    "start_time": "2026-10-09T00:00:00"
}`

// capturingLogger records resume-selection log lines.
type capturingLogger struct{ lines []string }

func (l *capturingLogger) Printf(format string, args ...any) {
	l.lines = append(l.lines, fmt.Sprintf(format, args...))
}

// TestReadPythonFixture reads the committed Python-written fixture
// (generated by generate_fixture.py through the REAL journalpump
// get_state/save_state code paths) and asserts the decoded schema.
func TestReadPythonFixture(t *testing.T) {
	t.Parallel()
	state, err := Read(pythonFixture)
	if err != nil {
		t.Fatalf("Read: %v", err)
	}
	reader, ok := state.Readers["reader_one"]
	if !ok {
		t.Fatalf("reader_one missing: %+v", state.Readers)
	}
	if reader.Cursor == nil || *reader.Cursor != "cursor=11223344-0" {
		t.Errorf("cursor = %v", reader.Cursor)
	}
	wantSearches := map[string]int64{"errors": 0, "payment_lines": 7}
	for name, hits := range wantSearches {
		if reader.Searches[name] != hits {
			t.Errorf("search %q hits = %d, want %d", name, reader.Searches[name], hits)
		}
	}
	if len(reader.Senders) != 2 {
		t.Fatalf("senders = %+v", reader.Senders)
	}
	// File order: sort_keys=True wrote kafka_backup first.
	if reader.Senders[0].Name != "kafka_backup" || reader.Senders[1].Name != "kafka_primary" {
		t.Errorf("sender order = [%s, %s]", reader.Senders[0].Name, reader.Senders[1].Name)
	}
	backup := reader.Senders[0].State
	if backup.Sent.Cursor != nil {
		t.Errorf("backup sent cursor = %v, want nil", backup.Sent.Cursor)
	}
	if backup.Health.Status != "stale" || backup.Type != "LogSender" {
		t.Errorf("backup = %+v", backup)
	}
	if backup.Buffer.CurrentQueue != 3 || backup.Buffer.EntryNum != 17 || backup.Buffer.TotalSize != 2048 {
		t.Errorf("backup buffer = %+v", backup.Buffer)
	}
	primary := reader.Senders[1].State
	if primary.Sent.Cursor == nil || *primary.Sent.Cursor != "cursor=aabbccdd-1" {
		t.Errorf("primary sent cursor = %v", primary.Sent.Cursor)
	}
	if primary.Sent.Count != 1234 || primary.Sent.Bytes != 5_000_000 {
		t.Errorf("primary sent = %+v", primary.Sent)
	}
	if primary.Health.Elapsed != 12.5 {
		t.Errorf("primary elapsed = %v, want 12.5", primary.Health.Elapsed)
	}
	if got := strings.Join(primary.Health.Errors, "|"); got != "Connection refused|Timed out" {
		t.Errorf("primary errors = %q", got)
	}
	if reader.TotalLines != 1_000_000 || reader.TotalBytes != 999_999_999 {
		t.Errorf("totals = %d/%d", reader.TotalLines, reader.TotalBytes)
	}
	if state.StartTime != "2026-10-09T12:00:00.000000" {
		t.Errorf("start_time = %q", state.StartTime)
	}
	// Resume: the alphabetically-FIRST sender has a null cursor, so the
	// walk aborts with a full resync even though kafka_primary has a
	// cursor.
	logger := &capturingLogger{}
	if got := ResumeCursor(reader, "reader_one", logger); got != nil {
		t.Errorf("resume cursor = %v, want nil (full resync)", got)
	}
	if len(logger.lines) != 1 || !strings.Contains(logger.lines[0], "needs full sync from beginning") {
		t.Fatalf("log lines = %q", logger.lines)
	}
}

// TestWriteRoundTripByteIdentical proves the Go writer is byte-faithful
// with Python's json.dump(indent=4, sort_keys=True): re-writing the
// decoded Python fixture reproduces the original file exactly.
func TestWriteRoundTripByteIdentical(t *testing.T) {
	t.Parallel()
	state, err := Read(pythonFixture)
	if err != nil {
		t.Fatalf("Read: %v", err)
	}
	want, err := os.ReadFile(pythonFixture)
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	path := filepath.Join(t.TempDir(), "state.json")
	if err := Write(path, state); err != nil {
		t.Fatalf("Write: %v", err)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	if string(got) != string(want) {
		t.Fatalf("rewrite differs from Python fixture\ngot:\n%s\nwant:\n%s", got, want)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("Stat: %v", err)
	}
	// Python's atomic_replace_file uses mkstemp without an explicit
	// mode, so the state file is 0600.
	if info.Mode().Perm() != 0o600 {
		t.Errorf("mode = %v, want 0600", info.Mode().Perm())
	}
}

// TestWriteGolden asserts the Go-written fixture byte-for-byte (the
// committed file is what the permanent Python interop test
// test/test_state_file_interop.py reads). Regenerate with:
// UPDATE_STATE_GOLDEN=1 go test ./internal/state/
func TestWriteGolden(t *testing.T) {
	t.Parallel()
	cursorPrimary := "cursor=primary-1"
	cursorBackup := "cursor=backup-2"
	bufferCursor := "cursor=buffer-3"
	state := &State{
		StartTime: "2026-10-09T13:00:00.000000",
		Readers: map[string]*ReaderState{
			"reader_two": {
				Cursor: &cursorPrimary,
				Searches: map[string]int64{
					"zeta":  3,
					"alpha": 10,
				},
				// Deliberately NON-sorted in-memory order: the writer
				// sorts on disk (sort_keys=True) and the health errors
				// list keeps its order (lists are not sorted).
				Senders: []NamedSenderState{
					{
						Name: "kafka_backup",
						State: SenderState{
							Type: "LogSender",
							Sent: SentState{Cursor: &cursorBackup, Count: 7, Bytes: 65_536},
							Health: HealthState{
								Status:  "connected",
								Elapsed: 3.5,
								Errors:  []string{"connection reset été", "first error stays"},
							},
							Buffer: BufferState{Cursor: &bufferCursor, TotalSize: 4096, EntryNum: 9, CurrentQueue: 2},
						},
					},
					{
						Name: "kafka_primary",
						State: SenderState{
							Type:   "LogSender",
							Sent:   SentState{Cursor: nil, Count: 0, Bytes: 0},
							Health: HealthState{Status: "stale", Elapsed: 0},
							Buffer: BufferState{Cursor: nil, TotalSize: 0, EntryNum: 0, CurrentQueue: 0},
						},
					},
				},
				TotalLines: 42,
				TotalBytes: 84,
			},
		},
	}

	path := filepath.Join(t.TempDir(), "state.json")
	if err := Write(path, state); err != nil {
		t.Fatalf("Write: %v", err)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}

	const goldenPath = "testdata/state_go_written.json"
	if os.Getenv("UPDATE_STATE_GOLDEN") == "1" {
		if err := os.WriteFile(goldenPath, got, 0o600); err != nil {
			t.Fatalf("WriteFile: %v", err)
		}
		t.Logf("updated %s", goldenPath)
		return
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("ReadFile: %v (regenerate with UPDATE_STATE_GOLDEN=1 go test ./internal/state/)", err)
	}
	if string(got) != string(want) {
		t.Fatalf("Go-written state differs from committed golden\ngot:\n%s\nwant:\n%s", got, want)
	}

	// The Go-written file must re-read identically (the sender order on
	// disk is sorted, so the decoded order follows the file).
	decoded, err := Read(goldenPath)
	if err != nil {
		t.Fatalf("Read: %v", err)
	}
	senders := decoded.Readers["reader_two"].Senders
	if senders[0].Name != "kafka_backup" || senders[1].Name != "kafka_primary" {
		t.Errorf("decoded sender order = [%s, %s]", senders[0].Name, senders[1].Name)
	}
	if errs := senders[0].State.Health.Errors; len(errs) != 2 || errs[0] != "connection reset été" {
		t.Errorf("errors order = %q (lists must keep their order)", errs)
	}
}

// TestResumeCursorLastListedWins is the quirk-lock test: the resume
// loop walks the senders in FILE key order, so the LAST listed sender
// wins even when it is not the alphabetically last (Python's
// sort_keys=True means captured Python-written files always order
// senders alphabetically and cannot exhibit the quirk; this fixture is
// hand-crafted, journalpump.py:890-905).
func TestResumeCursorLastListedWins(t *testing.T) {
	t.Parallel()
	state := readHandCrafted(t, quirkStateFile)
	reader := state.Readers["r"]
	// File order: zulu (cursor=Z) listed first, alpha (cursor=A) last.
	got := ResumeCursor(reader, "r", nil)
	if got == nil || *got != "cursor=A" {
		t.Errorf("resume cursor = %v, want cursor=A (last listed wins in key order)", got)
	}
}

// TestResumeCursorAnyMissingIsFullResync: ANY sender with a null
// sent.cursor aborts the walk — even a later sender with a cursor —
// with a full resync (nil).
func TestResumeCursorAnyMissingIsFullResync(t *testing.T) {
	t.Parallel()
	file := strings.Replace(quirkStateFile,
		`"sent": {"cursor": "cursor=Z"`, `"sent": {"cursor": null`, 1)
	state := readHandCrafted(t, file)
	reader := state.Readers["r"]
	if got := ResumeCursor(reader, "r", nil); got != nil {
		t.Errorf("resume cursor = %v, want nil (missing cursor aborts the walk)", got)
	}
}

// TestResumeCursorDefaultsToReaderCursor: a reader with no senders
// resumes from its own cursor.
func TestResumeCursorDefaultsToReaderCursor(t *testing.T) {
	t.Parallel()
	cursor := "cursor=reader-0"
	reader := &ReaderState{Cursor: &cursor, Searches: map[string]int64{}}
	got := ResumeCursor(reader, "r", nil)
	if got == nil || *got != cursor {
		t.Errorf("resume cursor = %v, want %q", got, cursor)
	}
}

